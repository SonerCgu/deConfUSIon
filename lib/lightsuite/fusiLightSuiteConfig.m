function cfg = fusiLightSuiteConfig(overrides)
% Paths are local preferences, never saved into the distributed toolbox.
root = fileparts(fileparts(fileparts(mfilename('fullpath'))));
external = fullfile(fileparts(root), 'deConfUSIon_ExternalTools');
cfg = struct('externalRoot', external, ...
    'lightSuite', fullfile(external, 'LightSuite'), ...
    'matlabElastix', fullfile(external, 'matlab_elastix'), ...
    'yamlMatlab', fullfile(external, 'yamlmatlab'), ...
    'bcpd', fullfile(external, 'bcpd', 'win'), ...
    'elastixBin', fullfile(external, 'elastix-5.1.0'), ...
    'allenAtlas', fullfile(external, 'Allen-CCF-2020'), ...
    'vascularAtlas', fullfile(external, 'fUS_vascular_atlas', 'fUS_vascular_atlas'), ...
    'bioformats', fullfile(external, 'bioformats-matlab', 'tbx', 'BioformatsImage'), ...
    'bfmatlab', fullfile(external, 'bfmatlab'), ...
    'pinnedCommit', '2cf948caaa96f1acac6e02917717499b2ba174ce', ...
    'outputFolder', '', 'voxelSizeMm', [], 'permutation', [3 1 2], ...
    'orientationConfirmed', false, 'maxTemplateFrames', 101, ...
    'landmarkWeight', 0.1, 'bsplineSpacingMm', 1.6, 'histogramBins', 48, ...
    'sourceFile', '', 'name', 'sample', 'maxAtlasMovieGiB', 2, ...
    'progressFcn', [], 'spacingSource', '');
if ispref('deConfUSIonLightSuite', 'paths')
    saved = getpref('deConfUSIonLightSuite', 'paths');
    names = fieldnames(saved);
    for k = 1:numel(names), if isfield(cfg,names{k}), cfg.(names{k})=saved.(names{k}); end, end
end
if nargin > 0 && ~isempty(overrides)
    names = fieldnames(overrides);
    for k = 1:numel(names)
        assert(isfield(cfg,names{k}), 'deConfUSIon:LightSuiteConfig', 'Unknown option: %s',names{k});
        cfg.(names{k})=overrides.(names{k});
    end
end
end
