function choice=fusiLightSuiteChoice(titleText,message,choices,descriptions)
% Readable dark modal selector; closing is cancellation, never acceptance.
if nargin<4,descriptions=repmat({''},size(choices));end
choice='';n=numel(choices);height=190+85*n;
f=figure('Name',titleText,'NumberTitle','off','MenuBar','none','ToolBar','none', ...
    'Color',[.035 .045 .045],'Position',[200 140 650 height],'Resize','off', ...
    'WindowStyle','modal','CloseRequestFcn',@cancel);
setappdata(f,'deConfUSIonNoMaximize',true);movegui(f,'center');
uicontrol(f,'Style','text','Units','pixels','Position',[25 height-68 600 40], ...
    'String',titleText,'FontName','Arial','FontSize',19,'FontWeight','bold', ...
    'HorizontalAlignment','left','BackgroundColor',f.Color,'ForegroundColor',[.9 .97 .94]);
uicontrol(f,'Style','text','Units','pixels','Position',[25 height-145 600 66], ...
    'String',message,'FontName','Arial','FontSize',12,'HorizontalAlignment','left', ...
    'BackgroundColor',f.Color,'ForegroundColor',[.68 .79 .75]);
for k=1:n
    y=height-160-k*85;
    h=uicontrol(f,'Style','pushbutton','Units','pixels','Position',[25 y+29 600 43], ...
        'String',choices{k},'FontName','Arial','FontSize',13,'FontWeight','bold', ...
        'BackgroundColor',[.08 .21 .16],'ForegroundColor',[.8 1 .9], ...
        'Callback',@(~,~)pick(k));setappdata(h,'PreserveColors',true);
    uicontrol(f,'Style','text','Units','pixels','Position',[30 y+2 590 25], ...
        'String',descriptions{k},'FontName','Arial','FontSize',10,'HorizontalAlignment','left', ...
        'BackgroundColor',f.Color,'ForegroundColor',[.65 .76 .71]);
end
uiwait(f);if isgraphics(f),delete(f);end
    function pick(index),choice=choices{index};uiresume(f);end
    function cancel(~,~),choice='';uiresume(f);end
end
