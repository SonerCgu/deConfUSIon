function candidate=fusiLightSuiteBuildInverse(forward,folder)
% Deterministic inverse optimization. A separate candidate is validated before
% any saved transform is replaced. DisplacementMagnitudePenalty minimizes the
% composed forward/inverse displacement; images supply the physical grid only.
assert(~isfolder(folder),'Choose a new inverse-candidate folder.');
header=elastix_parameter_read(forward);
assert(all(abs(double(header.Origin))<1e-9)&& ...
    all(abs(double(header.Direction(:)')-[1 0 0 0 1 0 0 0 1])<1e-9), ...
    'deConfUSIon:LightSuiteInverseGeometry','Inverse rebuilding requires the standard zero-origin, axis-aligned LightSuite registration grid.');
dims=double(header.Size([2 1 3]));
stride=max(1,ceil((prod(dims)/50000)^(1/3)));
params=struct('Registration','MultiResolutionRegistration', ...
    'Transform','RecursiveBSplineTransform','Metric','DisplacementMagnitudePenalty', ...
    'Optimizer','QuasiNewtonLBFGS','ImageSampler','Grid', ...
    'SampleGridSpacing',stride*[1 1 1],'NewSamplesEveryIteration',false, ...
    'NumberOfResolutions',1,'ImagePyramidSchedule',[1 1 1], ...
    'MaximumNumberOfIterations',600,'MaximumNumberOfLineSearchIterations',30, ...
    'StepLength',1,'ValueTolerance',1e-12,'GradientMagnitudeTolerance',1e-8, ...
    'FinalGridSpacingInPhysicalUnits',double(header.GridSpacing), ...
    'HowToCombineTransforms','Compose','AutomaticTransformInitialization',false, ...
    'AutomaticScalesEstimation',false,'UseDirectionCosines',true, ...
    'BSplineInterpolationOrder',3,'FinalBSplineInterpolationOrder',1, ...
    'FixedImageDimension',3,'MovingImageDimension',3, ...
    'FixedInternalImagePixelType','float','MovingInternalImagePixelType','float', ...
    'DefaultPixelValue',0,'ResultImagePixelType','float','ResultImageFormat','mhd', ...
    'WriteResultImage',false);
dummy=zeros(dims,'single');mkdir(folder);
[~,stats]=elastix(dummy,dummy,folder,-1,'paramstruct',params,'t0',{forward}, ...
    'movingscale',double(header.Spacing),'fixedscale',double(header.Spacing));
assert(iscell(stats.TransformParameters)&&~isempty(stats.TransformParameters), ...
    'deConfUSIon:LightSuiteInverseOptimization','Inverse optimization failed. Inspect the candidate elastix.log. The saved transform was not changed.');
inverse=stats.TransformParameters{end};
inverse.InitialTransformParametersFileName='NoInitialTransform';
candidate=fullfile(folder,'inverse_candidate.txt');
elastix_paramStruct2txt(candidate,inverse);
end
