function candidates=scmAtlasRankingCandidates(reports,opt,displayTR,displayNT)
% Adapt ranked volume regions to SCM's existing Target/Control review/export.
candidates={};labels=unique(cellfun(@(r)r.sourceScanLabel,reports,'UniformOutput',false),'stable');
for ri=1:numel(reports)
    r=reports{ri};s=r.settings;shape=r.shapeYXZ;
    role='Search';side='Combined';if isfield(r,'role'),role=r.role;side=r.imageSide;end
    for row=1:height(r.table)
        indices=r.regionVoxelIndices{row};[yy,xx,zz]=ind2sub(shape,double(indices));
        counts=accumarray(zz,1,[shape(3) 1]);[~,slice]=max(counts);
        region=struct('id',r.table.AtlasID(row),'acronym',r.table.Abbreviation{row}, ...
            'name',r.table.Region{row},'displayName',[r.table.Abbreviation{row} ' | ' r.table.Region{row}], ...
            'voxelCount',r.table.AtlasVoxels(row));
        value=r.table.ChangePSC_pct(row);score=value;
        if strcmp(s.direction,'decrease'),score=-value;elseif strcmp(s.direction,'absolute'),score=abs(value);end
        top=0;if isfield(opt,'topCount'),top=opt.topCount(1);if numel(opt.topCount)==2&&strcmp(role,'Control'),top=opt.topCount(2);end,end
        c=struct('slice',slice,'activeSlices',unique(zz(:)'),'role',role,'region',[region.displayName ' / ' side], ...
            'atlasRegion',region,'roiMode','atlasRanking','boundsXY',[min(xx) max(xx) min(yy) max(yy)], ...
            'roiMaskVolumeIndices',indices,'roiMaskSizeYXZ',shape,'pixelCount',numel(indices), ...
            'sizeXYUm',[NaN NaN],'requestedSizeUm',[NaN NaN],'meanPSC',r.table.MeanPSC_pct(row), ...
            'rankingValue',value,'rankingScore',score,'coveragePercent',r.table.Coverage_pct(row), ...
            'minimumUsableCoverageFraction',s.minCoverage,'originalImageSide',side, ...
            'peakPSC',r.table.PeakPSC_pct(row),'peakSampleSec',r.table.PeakTime_min(row)*60, ...
            'rankingReportIndex',ri,'rankingRow',row,'selectionRank',r.table.Rank(row),'requestedTopN',top, ...
            'signalSec',s.signalSec,'signalSampleSec',s.signalSampleSec,'baselineSec',s.baselineSec, ...
            'baselineSampleSec',s.baselineSampleSec,'baselineMode',s.baselineMode, ...
            'sourceSignalFrames',s.signalFrames,'sourceBaselineFrames',s.baselineFrames, ...
            'signalFrames',unique(max(1,min(displayNT,round(s.signalSampleSec/displayTR)+1))), ...
            'baselineFrames',unique(max(1,min(displayNT,round(s.baselineSampleSec/displayTR)+1))), ...
            'searchIntervalSec',s.signalSec,'plateauSec',0,'windowMode','whole-interval', ...
            'searchedSlices',s.sliceRange(1):s.sliceRange(2),'searchBoundsXY',[1 shape(2) 1 shape(1)], ...
            'leftIsTarget',true,'splitX',floor(shape(2)/2),'ventriclesExcluded',true, ...
            'excludedAtlasIDs',r.excludedAtlasIDs,'minimumAtlasCoverageFraction',1,'atlasCoverageFraction',1, ...
            'searchScanKey',r.sourceScanKey,'searchScanLabel',r.sourceScanLabel,'searchTR',r.TR, ...
            'searchScanIndex',r.sourceScanIndex,'searchScanCode',char('A'+r.sourceScanIndex-1), ...
            'searchTrace',r.traces(row,:),'searchTraceValid',true,'selection',r.method);
        if strcmp(c.baselineMode,'external')
            c.baselineReference=r.sourceBaseline.reference;
            c.baselineSampleSec=c.baselineReference.windowSec;c.baselineSec=c.baselineSampleSec;
            c.baselineFrames=1;c.sourceBaselineFrames=c.baselineReference.frames;
        end
        p=struct('TR',r.TR,'roiSelection','Both','topCount',opt.topCount,'bilateral',false, ...
            'hasPaintMask',false,'uploadedMaskApplied',false,'displayMode','keep', ...
            'searchedScanLabels',{labels},'rankingMetric',s.metric,'rankingDirection',s.direction);
        p.minUsableCoverage=s.minCoverage;
        if isfield(opt,'atlasRegions'),p.selectedAtlasRegions=opt.atlasRegions;end
        if isfield(opt,'roiSelection'),p.roiSelection=opt.roiSelection;end
        if isfield(opt,'bilateral'),p.bilateral=opt.bilateral;end
        if isfield(opt,'leftIsTarget'),c.leftIsTarget=opt.leftIsTarget;end
        if isfield(opt,'splitX'),c.splitX=opt.splitX;end
        if isfield(opt,'midlineXY'),c.midlineXY=opt.midlineXY;p.midlineXY=opt.midlineXY;end
        if isfield(s,'atlasProvenance'),c.atlasProvenance=s.atlasProvenance;end
        c.searchParameters=p;candidates{end+1}=c; %#ok<AGROW>
    end
end
end
